import { useEffect, useId, useMemo, useRef, useState, type FormEvent } from 'react'
import { api } from '../../api/client'
import {
  AVATAR_BACKENDS,
  BACKEND_LABELS,
  PHOTO_BACKENDS,
  type AvatarBackend,
  type Persona,
  type PersonaCreate,
} from '../../api/types'
import { CloseIcon, UploadIcon } from '../icons'

const MAX_PHOTO_BYTES = 10 * 1024 * 1024
const PHOTO_TYPES = ['image/jpeg', 'image/png', 'image/webp']

const BACKEND_HINTS: Record<AvatarBackend, string> = {
  simli: 'Photoreal video face generated by Simli from your photo.',
  flashhead: 'Self-hosted photoreal video avatar (GPU) driven by your photo.',
  browser3d: 'Animated 3D character rendered in your browser. No photo needed.',
  none: 'Voice only, with an audio visualiser.',
}

/** A few Cartesia sonic-3 voices so the voice can match the face; any other ID via "Custom". */
const VOICES: { id: string; label: string }[] = [
  { id: '30894953-bcce-41fe-892c-15ce19c843ff', label: 'Parker: warm, friendly (male, US)' },
  { id: '47c38ca4-5f35-497b-b1a3-415245fb35e1', label: 'Daniel: clear, crisp (male, US)' },
  { id: 'ef191366-f52f-447a-a398-ed8c0f2943a1', label: 'Archie: warm, casual (male, UK)' },
  { id: '0ad65e7f-006c-47cf-bd31-52279d487913', label: 'Rupert: mature, reassuring (male)' },
  { id: '4877b818-c7fe-4c89-b1cf-eadf8e23da72', label: 'Rohan: measured (male, Indian)' },
  { id: 'db6b0ed5-d5d3-463d-ae85-518a07d3c2b4', label: 'Skylar: friendly (female, US)' },
  { id: 'e8e5fffb-252c-436d-b842-8879b84445b6', label: 'Cathy: casual, young (female, US)' },
  { id: '62ae83ad-4f6a-430b-af41-a9bede9286ca', label: 'Gemma: confident (female, UK)' },
  { id: '273f9ef7-9fc2-4def-88bb-ab108c6249ca', label: 'Julia: soft, gentle (female)' },
]
const CUSTOM_VOICE = 'custom'

interface Props {
  onClose(): void
  /** Called after create (and photo upload, if any). `warning` = created but photo upload failed. */
  onCreated(p: Persona, warning?: string): void
}

export function NewPersonaDialog({ onClose, onCreated }: Props) {
  const dialogRef = useRef<HTMLDialogElement>(null)
  const ids = useId()
  const [name, setName] = useState('')
  const [prompt, setPrompt] = useState('')
  const [backend, setBackend] = useState<AvatarBackend>('simli')
  const [voiceChoice, setVoiceChoice] = useState('')
  const [voiceId, setVoiceId] = useState('')
  const [photo, setPhoto] = useState<File | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [submitting, setSubmitting] = useState(false)

  useEffect(() => {
    const d = dialogRef.current
    if (d && !d.open) d.showModal()
  }, [])

  const preview = useMemo(() => (photo ? URL.createObjectURL(photo) : null), [photo])
  useEffect(() => {
    if (preview) return () => URL.revokeObjectURL(preview)
  }, [preview])

  const photoRequired = PHOTO_BACKENDS.includes(backend)

  const pickPhoto = (file: File | undefined) => {
    setError(null)
    if (!file) return
    if (!PHOTO_TYPES.includes(file.type)) return setError('Photo must be a JPG, PNG or WebP image.')
    if (file.size > MAX_PHOTO_BYTES) return setError('Photo must be 10 MB or smaller.')
    setPhoto(file)
  }

  const submit = async (e: FormEvent) => {
    e.preventDefault()
    setError(null)
    if (!name.trim()) return setError('Give the persona a name.')
    if (photoRequired && !photo) return setError(`A face photo is required for ${BACKEND_LABELS[backend]}.`)

    const body: PersonaCreate = { name: name.trim(), avatar_backend: backend }
    if (prompt.trim()) body.system_prompt = prompt.trim()
    const voice = voiceChoice === CUSTOM_VOICE ? voiceId.trim() : voiceChoice
    if (voice) body.voice = { provider: 'cartesia', model: 'sonic-3', voice_id: voice }

    setSubmitting(true)
    let created: Persona
    try {
      created = await api.createPersona(body)
    } catch (err) {
      setSubmitting(false)
      return setError(`Could not create persona: ${err instanceof Error ? err.message : String(err)}`)
    }
    if (photo) {
      try {
        created = await api.uploadPhoto(created.id, photo)
      } catch (err) {
        setSubmitting(false)
        onCreated(created, `Persona created, but the photo upload failed: ${err instanceof Error ? err.message : String(err)}`)
        return
      }
    }
    setSubmitting(false)
    onCreated(created)
  }

  return (
    <dialog
      ref={dialogRef}
      className="modal"
      onClose={onClose}
      onCancel={(e) => {
        if (submitting) e.preventDefault()
      }}
      aria-labelledby={`${ids}-title`}
    >
      <form className="modal-card" onSubmit={(e) => void submit(e)}>
        <header className="modal-header">
          <h2 id={`${ids}-title`}>New persona</h2>
          <button type="button" className="btn ghost icon-only" onClick={onClose} aria-label="Close" disabled={submitting}>
            <CloseIcon />
          </button>
        </header>

        <div className="modal-body">
          <div className="form-grid">
            <div className="photo-field">
              <label className={`photo-drop ${preview ? 'has-photo' : ''}`} htmlFor={`${ids}-photo`}>
                {preview ? (
                  <img src={preview} alt="Selected photo preview" />
                ) : (
                  <span className="photo-drop-empty">
                    <UploadIcon width={26} height={26} />
                    <span>{photoRequired ? 'Face photo (required)' : 'Photo (optional)'}</span>
                    <small>JPG, PNG or WebP, up to 10 MB</small>
                  </span>
                )}
              </label>
              <input
                id={`${ids}-photo`}
                name="photo"
                type="file"
                accept={PHOTO_TYPES.join(',')}
                className="visually-hidden"
                onChange={(e) => pickPhoto(e.target.files?.[0])}
              />
              {photo && (
                <button type="button" className="btn ghost sm" onClick={() => setPhoto(null)}>
                  Remove photo
                </button>
              )}
            </div>

            <div className="fields">
              <label className="field">
                <span>Name</span>
                <input
                  name="name"
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="e.g. Ava"
                  maxLength={80}
                  autoFocus
                  required
                />
              </label>

              <label className="field">
                <span>Avatar</span>
                <select name="avatar_backend" value={backend} onChange={(e) => setBackend(e.target.value as AvatarBackend)}>
                  {AVATAR_BACKENDS.map((b) => (
                    <option key={b} value={b}>
                      {BACKEND_LABELS[b]}
                    </option>
                  ))}
                </select>
                <small className="field-hint">{BACKEND_HINTS[backend]}</small>
              </label>

              <label className="field">
                <span>Voice</span>
                <select name="voice" value={voiceChoice} onChange={(e) => setVoiceChoice(e.target.value)}>
                  <option value="">Default voice (female)</option>
                  {VOICES.map((v) => (
                    <option key={v.id} value={v.id}>
                      {v.label}
                    </option>
                  ))}
                  <option value={CUSTOM_VOICE}>Custom Cartesia voice ID…</option>
                </select>
                {voiceChoice === CUSTOM_VOICE && (
                  <input
                    name="voice_id"
                    value={voiceId}
                    onChange={(e) => setVoiceId(e.target.value)}
                    placeholder="Cartesia voice ID"
                    spellCheck={false}
                    autoComplete="off"
                  />
                )}
                <small className="field-hint">Pick one that matches the face.</small>
              </label>
            </div>
          </div>

          <label className="field">
            <span>
              System prompt <em>optional</em>
            </span>
            <textarea
              name="system_prompt"
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              rows={4}
              placeholder="Who is this persona, and how should they talk? Leave empty for the default."
            />
          </label>

          {error && (
            <p className="form-error" role="alert">
              {error}
            </p>
          )}
        </div>

        <footer className="modal-footer">
          <button type="button" className="btn ghost" onClick={onClose} disabled={submitting}>
            Cancel
          </button>
          <button type="submit" className="btn primary" disabled={submitting}>
            {submitting ? (photo ? 'Uploading…' : 'Creating…') : 'Create persona'}
          </button>
        </footer>
      </form>
    </dialog>
  )
}
